// One rectangle per run of the same pixel in a row.
function path(rows, ch) {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== ch) continue;
      let end = x;
      while (row[end] === ch) end++;
      d += `M${x} ${y}h${end - x}v1h-${end - x}z`;
      x = end - 1;
    }
  });
  return d;
}

const cache = {};
export function instIcon(type) {
  const key = type in ART ? type : 'other';
  if (!cache[key]) {
    const rows = ART[key].trim().split('\n').map(r => r.trim());
    cache[key] = `<svg class="ico" viewBox="0 0 16 16" aria-hidden="true"><path d="${path(rows, '#')}"/><path d="${path(rows, '+')}" opacity=".35"/></svg>`;
  }
  return cache[key];
}
